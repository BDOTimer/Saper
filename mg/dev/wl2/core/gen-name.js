// ─────────────────────────────────────────────────────────────────────
//  Детерминированный хеш индекса (murmur3-подобный)
//  Используется и WorldMap, и NameGenerator.
// ─────────────────────────────────────────────────────────────────────
function hashIdx(idx, salt = 0) {
  let h = (idx | 0) ^ 0x9e3779b9 ^ (salt | 0);
  h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
  h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
  h ^= h >>> 16;
  return h >>> 0;
}

