export class HeroNameGenerator {
  constructor(opts = {}) {
    this.seed = (opts.seed ?? 0) | 0;
    this.styles = STYLES;

    // названия рас по умолчанию (8 рас = 8 игроков)
    this.raceNames = [
      'Люди', 'Эльфы', 'Гномы', 'Орки',
      'Тролли', 'Тёмные эльфы', 'Нежить', 'Демоны',
    ];

    // ключи стилей по индексу игрока (0..7)
    this.raceStyles = [
      'hero_human', 'hero_elf', 'hero_dwarf', 'hero_orc',
      'hero_troll', 'hero_darkelf', 'hero_undead', 'hero_demon',
    ];

    // счётчики: сколько имён уже выдано каждому игроку
    this._counters = new Array(8).fill(0);
    // множества выданных имён (глобально по игре)
    this._usedFirst = new Set();
    this._usedFull  = new Set();
  }

  /** Название расы по индексу игрока (0..7). */
  race(idx) {
    const i = (idx | 0) & 7;
    return this.raceNames[i];
  }

  /** Установить новые названия рас. */
  set(raceNames) {
    if (Array.isArray(raceNames)) {
      for (let i = 0; i < 8; i++) {
        if (raceNames[i] != null) this.raceNames[i] = String(raceNames[i]);
      }
    }
    return this;
  }

  /** УНИКАЛЬНОЕ имя героя для игрока idx (0..7). */
  hero(idx) {
    const i = (idx | 0) & 7;
    const st = this._style(i);
    let guard = 0;
    while (guard++ < 100000) {
      const n = this._buildFirst(this._counters[i]++, st);
      if (!this._usedFirst.has(n)) {
        this._usedFirst.add(n);
        return n;
      }
    }
    // лексикон исчерпан — числовой суффикс
    const n = this._buildFirst(this._counters[i]++, st) + ' ' + guard;
    this._usedFirst.add(n);
    return n;
  }

  /** УНИКАЛЬНОЕ ПОЛНОЕ имя героя для игрока idx (0..7). */
  heroFull(idx) {
    const i = (idx | 0) & 7;
    const st = this._style(i);
    let guard = 0;
    while (guard++ < 100000) {
      const n = this._buildFull(this._counters[i]++, st);
      if (!this._usedFull.has(n)) {
        this._usedFull.add(n);
        return n;
      }
    }
    const n = this._buildFull(this._counters[i]++, st) + ' ' + guard;
    this._usedFull.add(n);
    return n;
  }

  // ───────────────────────── внутреннее ──────────────────────────────

  _style(i) {
    return this.styles[this.raceStyles[i]] || this.styles.hero_human;
  }

  _buildFirst(idx, st) {
    const base = hashIdx(idx, this.seed);
    const p = st.pre[base % st.pre.length];
    const m = st.mid ? st.mid[((base >>> 8) >>> 0) % st.mid.length] : '';
    const s = st.suf ? st.suf[((base >>> 16) >>> 0) % st.suf.length] : '';
    return this._smooth(p + m + s);
  }

  _buildFull(idx, st) {
    const first = this._buildFirst(idx, st);
    if (!st.sur || !st.sur.length) return first;
    const surIdx = hashIdx(idx, this.seed ^ 0x9b1) % st.sur.length;
    const last = this._smoothWord(st.sur[surIdx]);
    return last ? `${first} ${last}` : first;
  }

  _smooth(s) {
    s = s.replace(/([а-яё])\1\1/gi, '$1$1');
    s = s.replace(/[ъь](?=[аеёиоуыэюя])/gi, '');
    s = s.replace(/([аеёиоуыэюя])\1/gi, '$1');
    if (s) s = s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
    return s;
  }

  _smoothWord(s) {
    if (!s) return '';
    return s.charAt(0).toUpperCase() + s.slice(1).toLowerCase();
  }
}

